// Maxroll's Special Hones upgrade calculator. Maxroll shares provenance with our
// datamine author (sekwahar), so this is a trusted source (see project memory).
// TJW_DEFAULT_PRICES exists ONLY for the one-time port parity test; live valuation
// always uses our own price map.
//
// Shape notes (extracted, not assumed). His rows are 10-element tuples destructured as
// [level, success, failBonus, failMax, additiveMax, juiceChance, juiceLimit, taps, mats, extra].
// Rates are fixed point in 0.01% units, so 1e4 = 100% (his engine divides chances by 1e4 and
// compares accumulated artisan energy against ARTISAN_THRESHOLD in the same units). The mats
// and additive keys are his price-catalog column names, not our slugs; TJW_MAT_PRICE_KEY maps
// the mats columns onto catalog keys. His hone cost also folds in two hardcoded rates that are
// not in the catalog: silver x1 (his Om) and shards x0.25 (his Am).

export type HoneKind = "transferred" | "circulated";
export type HoneSlot = "weapon" | "armor";
export type HoneMatKey = "Fusions" | "Stones" | "Leapstones" | "Base blue stones";

export interface HoneLevelRow {
  level: number;
  success: number; // base success rate in 0.01% units (1e4 = 100%)
  failBonus: number; // success added per failed attempt
  failMax: number; // cap on the accumulated fail bonus
  additiveMax: number; // cap on the success juice can add
  juiceChance: number; // success added per juice unit
  juiceLimit: number; // max juice units per attempt
  tapsPerAttempt: number; // Special Hone (free tap) tickets one attempt at this level costs
  mats: Partial<Record<HoneMatKey, number>>;
  extra: { silver: number; shards: number };
}

export interface HoneSlotTable {
  additiveKey: string; // price-catalog key of the juice this slot uses
  levels: HoneLevelRow[];
}

